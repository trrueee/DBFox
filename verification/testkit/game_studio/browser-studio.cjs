async (page) => {
  const assert = (condition, message) => { if (!condition) throw new Error(message); };
  const stats = () => page.locator('.game-preview-stats').innerText();
  const tick = async () => Number((await stats()).match(/tick (\d+)/)[1]);
  const inspect = () => page.evaluate(async () => {
    const gameId = document.querySelector('[aria-label="选择游戏"]').value;
    const invoke = async (name, input) => {
      const response = await fetch('/operation', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ name, input }) });
      if (!response.ok) throw new Error(await response.text());
      return response.json();
    };
    const { readGame } = await import('/dlcs/dbfox.game/frontend/model.js');
    return readGame(invoke, gameId);
  });
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.getByRole('button', { name: '重置', exact: true }).click();
  await page.waitForFunction(() => document.querySelector('.game-preview-stats')?.textContent.includes('tick 0'));
  await page.getByRole('button', { name: '单步', exact: true }).click();
  assert(await tick() === 1, 'Single step must advance exactly once');
  await page.getByRole('button', { name: '播放', exact: true }).click();
  await page.waitForFunction(() => Number(document.querySelector('.game-preview-stats')?.textContent.match(/tick (\d+)/)?.[1]) >= 10);
  await page.getByRole('button', { name: '暂停', exact: true }).click();
  const paused = await tick();
  await page.waitForTimeout(160);
  assert(await tick() === paused, 'Pause must stop simulation');
  await page.getByRole('button', { name: '重置', exact: true }).click();
  await page.waitForFunction(() => document.querySelector('.game-preview-stats')?.textContent.includes('tick 0'));
  const before = await inspect();
  const fox = before.document.entities.find((entity) => entity.tags.includes('player'));
  const transform = fox.components.find((component) => component.spec.kind === 'transform');
  const scene = before.document.scenes.find((item) => item.id === fox.scene_id);
  const canvas = await page.locator('.game-canvas-parent canvas').boundingBox();
  const x = canvas.x + transform.spec.x / scene.width * canvas.width;
  const y = canvas.y + transform.spec.y / scene.height * canvas.height;
  await page.mouse.move(x, y); await page.mouse.down(); await page.mouse.move(x + canvas.width / 10, y, { steps: 5 }); await page.mouse.up();
  await page.waitForFunction((version) => document.querySelector('.game-header .game-badge')?.textContent === `v${version}`, before.revision.version + 1);
  const moved = await inspect();
  const movedTransform = moved.document.entities.find((item) => item.id === fox.id).components.find((item) => item.id === transform.id);
  assert(movedTransform.spec.x === transform.spec.x + scene.width / 10, 'Drag must persist transformed coordinates');
  assert(moved.document.rules.length === before.document.rules.length, 'Drag must preserve unrelated rules');
  await page.locator('.game-component-card').filter({ has: page.getByRole('heading', { name: '变换', exact: true }) }).getByRole('button', { name: '编辑', exact: true }).click();
  const numeric = page.getByRole('spinbutton', { name: 'X', exact: true });
  await numeric.fill('');
  assert(await numeric.getAttribute('type') === 'number', 'Cleared number must retain numeric input');
  await numeric.fill(String(transform.spec.x + 20));
  await page.getByRole('button', { name: '保存修改', exact: true }).click();
  await page.waitForFunction((version) => document.querySelector('.game-header .game-badge')?.textContent === `v${version}`, moved.revision.version + 1);
  const edited = await inspect();
  assert(edited.document.entities.find((item) => item.id === fox.id).components.find((item) => item.id === transform.id).spec.x === transform.spec.x + 20, 'Numeric field must save number after clearing');
  await page.getByRole('button', { name: '撤销上个版本', exact: true }).click();
  await page.waitForFunction((version) => document.querySelector('.game-header .game-badge')?.textContent === `v${version}`, edited.revision.version + 1);
  const restored = await inspect();
  assert(restored.revision.content_hash === moved.revision.content_hash, 'Undo must restore the exact document with a new version');
  await page.getByRole('button', { name: '版本历史', exact: true }).click();
  await page.locator('.game-history-row').first().waitFor();
  await page.evaluate(() => document.querySelector('.game-studio').scrollTo(0, 0));
  await page.screenshot({ path: '.tmp/game-phaser-review/studio-wide.png', fullPage: true });
  await page.setViewportSize({ width: 430, height: 930 });
  await page.evaluate(() => document.querySelector('.game-studio').scrollTo(0, 0));
  const layout = await page.evaluate(() => ({ width: document.documentElement.clientWidth, scroll: document.documentElement.scrollWidth }));
  assert(layout.scroll <= layout.width + 1, 'Narrow Studio must not overflow horizontally');
  await page.screenshot({ path: '.tmp/game-phaser-review/studio-narrow.png', fullPage: true });
  const report = { initialVersion: before.revision.version, finalVersion: restored.revision.version, singleStep: true, pause: true, reset: true, durableDrag: true, numericClear: true, undoExactHash: true, narrowLayout: layout };
  await page.evaluate(() => window.unmountGame());
  await page.waitForFunction(() => document.querySelectorAll('canvas').length === 0);
  return { ...report, unmountCanvasCount: await page.locator('canvas').count() };
}
