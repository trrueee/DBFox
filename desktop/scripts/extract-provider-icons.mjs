/* Regenerate offline provider marks: Simple Icons (CC0) and pinned Lobe SVGs (MIT). */
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { DOMParser } from "@xmldom/xmldom";

const require = createRequire(import.meta.url);
const si = require("simple-icons");

const WANTED = {
  anthropic: "siAnthropic",
  deepseek: "siDeepseek",
  moonshot: "siMoonshotai",
  qwen: "siQwen",
  alibabacloud: "siAlibabacloud",
  bytedance: "siBytedance",
  minimax: "siMinimax",
  baidu: "siBaidu",
  openrouter: "siOpenrouter",
  ollama: "siOllama",
  google: "siGooglegemini",
  mistral: "siMistralai",
  huggingface: "siHuggingface",
  perplexity: "siPerplexity",
  xiaomi: "siXiaomi",
};

const marks = {};
for (const [id, key] of Object.entries(WANTED)) {
  const icon = si[key];
  if (!icon) throw new Error(`Missing upstream provider mark: ${key}`);
  marks[id] = { path: icon.path, fillRule: "nonzero" };
}
const manifest = JSON.parse(readFileSync(new URL("../assets/lobe/manifest.json", import.meta.url), "utf8"));
for (const icon of manifest.icons) {
  if (!/^[a-z]+\.svg$/.test(icon.file) || marks[icon.provider]) throw new Error(`Invalid brand asset: ${icon.file}`);
  const bytes = readFileSync(new URL(`../assets/lobe/${icon.file}`, import.meta.url));
  if (createHash("sha256").update(bytes).digest("hex") !== icon.sha256) throw new Error(`Brand source hash changed: ${icon.file}`);
  const root = new DOMParser().parseFromString(bytes.toString("utf8"), "image/svg+xml").documentElement;
  const paths = root.getElementsByTagName("path");
  if (root.getAttribute("viewBox") !== "0 0 24 24" || paths.length !== 1 || paths[0].attributes.length > 2) throw new Error(`Unexpected brand geometry: ${icon.file}`);
  marks[icon.provider] = { path: paths[0].getAttribute("d"), fillRule: root.getAttribute("fill-rule") || "nonzero" };
}
const output = [
  "// Generated by scripts/extract-provider-icons.mjs. Do not edit.",
  "// Simple Icons (CC0); five pinned Lobe marks (MIT): assets/lobe/manifest.json and LICENSE.",
  'export const PROVIDER_ICONS: Readonly<Record<string, { path: string; fillRule: "nonzero" | "evenodd" }>> = Object.freeze({',
  ...Object.entries(marks).map(([id, mark]) => `  ${id}: ${JSON.stringify(mark)},`),
  "});", "",
].join("\n");
const target = new URL("../src/components/brand/providerPaths.ts", import.meta.url);
if (process.argv.includes("--check")) {
  if (readFileSync(target, "utf8") !== output) throw new Error("Provider marks are stale; run npm run generate:icons");
} else writeFileSync(target, output);
console.log(`${Object.keys(marks).length} offline provider marks verified`);
