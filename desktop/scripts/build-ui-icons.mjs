import { createHash } from "node:crypto";
import { readFile, readdir, mkdir, writeFile, unlink } from "node:fs/promises";
import { resolve, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";
import { DOMImplementation, DOMParser, XMLSerializer } from "@xmldom/xmldom";

const desktop = resolve(import.meta.dirname, "..");
const artworkRoot = resolve(desktop, "assets/phosphor");
const outputRoot = resolve(desktop, "public/assets/ui-icons");
const exportsFile = resolve(desktop, "src/components/icons/index.ts");
const namespace = "http://www.w3.org/2000/svg";
const weights = ["regular", "duotone", "fill"];
const elements = new Set(["svg", "g", "path", "rect", "circle", "ellipse", "line", "polyline", "polygon"]);
const digest = bytes => createHash("sha256").update(bytes).digest("hex");

function validate(element) {
  if (!elements.has(element.localName) || element.namespaceURI !== namespace) throw new Error(`Unsupported SVG element: ${element.nodeName}`);
  for (let i = 0; i < element.attributes.length; i += 1) {
    const { name, value } = element.attributes.item(i);
    if (/^on/i.test(name) || ["style", "href", "xlink:href"].includes(name) || /url\s*\(/i.test(value)) throw new Error(`Unsupported SVG attribute: ${name}`);
  }
  for (const child of Array.from(element.childNodes)) if (child.nodeType === 1) validate(child);
}

export async function buildUiIcons({ check = false } = {}) {
  const manifest = JSON.parse(await readFile(resolve(artworkRoot, "manifest.json"), "utf8"));
  const document = new DOMImplementation().createDocument(namespace, "svg", null);
  const root = document.documentElement;
  root.setAttribute("xmlns", namespace);
  const names = new Set();
  for (const icon of manifest.icons) {
    if (!/^[A-Z][A-Za-z0-9]*Icon$/.test(icon.name) || !/^[a-z]+(?:-[a-z0-9]+)*$/.test(icon.slug) || names.has(icon.name) || !weights.includes(icon.defaultWeight ?? "regular")) throw new Error(`Invalid icon manifest entry: ${icon.name}`);
    names.add(icon.name);
    for (const weight of weights) {
      const variant = icon.variants[weight];
      const path = resolve(artworkRoot, variant.file);
      if (!path.startsWith(artworkRoot + sep)) throw new Error("Icon source escapes its asset directory");
      const bytes = await readFile(path);
      if (digest(bytes) !== variant.sha256) throw new Error(`Upstream icon hash changed: ${variant.file}`);
      const parser = new DOMParser({ errorHandler: { warning: message => { throw new Error(message); }, error: message => { throw new Error(message); }, fatalError: message => { throw new Error(message); } } });
      const source = parser.parseFromString(bytes.toString("utf8"), "image/svg+xml").documentElement;
      validate(source);
      if (source.getAttribute("viewBox") !== "0 0 256 256") throw new Error(`Unexpected icon viewBox: ${variant.file}`);
      const symbol = document.createElementNS(namespace, "symbol");
      symbol.setAttribute("id", `${icon.slug}-${weight}`);
      symbol.setAttribute("viewBox", "0 0 256 256");
      for (let i = 0; i < source.attributes.length; i += 1) {
        const attribute = source.attributes.item(i);
        if (!["xmlns", "width", "height", "viewBox"].includes(attribute.name)) symbol.setAttribute(attribute.name, attribute.value);
      }
      for (const child of Array.from(source.childNodes)) if (child.nodeType === 1) symbol.appendChild(document.importNode(child, true));
      root.appendChild(symbol);
    }
  }
  const svg = new XMLSerializer().serializeToString(document) + "\n";
  const name = `phosphor-${digest(svg).slice(0, 12)}.svg`;
  const exports = [
    "// Generated by scripts/build-ui-icons.mjs from pinned, hash-checked upstream SVGs.",
    "// Do not edit glyph definitions here. See assets/phosphor/manifest.json and LICENSE.",
    'import { createIcon } from "./icon";',
    'export type { IconComponent, IconProps, IconWeight } from "./icon";',
    `const sprite = \`\${import.meta.env.BASE_URL}assets/ui-icons/${name}\`;`,
    ...manifest.icons.map(icon => `export const ${icon.name} = /* @__PURE__ */ createIcon(sprite, "${icon.slug}", "${icon.defaultWeight ?? "regular"}");`),
    "",
  ].join("\n");
  const svgPath = resolve(outputRoot, name);
  if (check) {
    if (await readFile(svgPath, "utf8") !== svg || await readFile(exportsFile, "utf8") !== exports) throw new Error("UI icon assets are stale; run npm run generate:icons");
  } else {
    await mkdir(outputRoot, { recursive: true });
    await mkdir(resolve(exportsFile, ".."), { recursive: true });
    await writeFile(svgPath, svg);
    await writeFile(exportsFile, exports);
    for (const file of await readdir(outputRoot)) if (/^phosphor-[a-f0-9]{12}\.svg$/.test(file) && file !== name) await unlink(resolve(outputRoot, file));
  }
  return { icons: names.size, variants: names.size * weights.length, bytes: Buffer.byteLength(svg), asset: relative(desktop, svgPath).replaceAll("\\", "/") };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  console.log(JSON.stringify(await buildUiIcons({ check: process.argv.includes("--check") })));
}
